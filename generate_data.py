def build_exposure(rain_grid, fires_all, dem_pts, glofas, ls_layer):
    log('B2+B4 ► District population masking + exposure summary…')
    exposure = []
    for d in DISTRICTS:
        nr = min(rain_grid, key=lambda r: hav(d['lat'],d['lon'],r['lat'],r['lon']))
        nf = [f for f in fires_all if hav(d['lat'],d['lon'],f['lat'],f['lon'])<80]
        fb = [f for f in nf if in_buf(f['lat'],f['lon'])]
        nd = min(dem_pts, key=lambda p: hav(d['lat'],d['lon'],p['lat'],p['lon']))
        ng = min(glofas.values(), key=lambda g: hav(d['lat'],d['lon'],g['lat'],g['lon']))
        nl = min(ls_layer, key=lambda l: hav(d['lat'],d['lon'],l['lat'],l['lon']))
        cpec = in_buf(d['lat'],d['lon'])
        ss = {'High':40,'Medium':20,'Low':5}.get(nd.get('slope_cat','Low'),5)
        rs = min(25, nr['rain_mm']*1.8)
        fs = min(20, len(nf)*4)
        fls = {'CRITICAL':15,'HIGH':10,'WATCH':5,'NORMAL':0}.get(ng['status'],0)
        score = min(100, round(ss+rs+fs+fls+(10 if cpec else 0)))
        level = 'Critical' if score>=75 else 'High' if score>=50 else 'Moderate' if score>=25 else 'Low'
        exposure.append(dict(
            district=d['n'],province=d['p'],lat=d['lat'],lon=d['lon'],population=d['pop'],
            cpec_flag='YES' if cpec else 'NO',
            rain_mm=nr['rain_mm'],anomaly_pct=nr['anomaly_pct'],
            fire_count=len(nf),fires_in_buffer=len(fb),
            elev_m=nd.get('elev',200),slope_cat=nd.get('slope_cat','Low'),
            flood_status=ng['status'],flood_pct_ltm=ng['maxPct'],
            landslide_level=nl['ls_level'],landslide_score=nl['ls_score'],
            risk_score=score,risk_level=level
        ))
    crit = sum(1 for e in exposure if e['risk_level']=='Critical')
    log(f'B4 ✓ {len(exposure)} districts | {crit} Critical risk')
    # CSV
    fields = [k for k in exposure[0] if k not in('lat','lon')]
    with open(OUTPUT/'district_exposure_summary.csv','w',newline='') as f:
        w = csv.DictWriter(f,fieldnames=fields+['lat','lon'])
        w.writeheader(); w.writerows(exposure)
    # Choropleth GeoJSON
    off = 0.4
    feats = [{'type':'Feature','properties':{k:v for k,v in e.items()},
        'geometry':{'type':'Polygon','coordinates':[[[e['lon']-off,e['lat']-.3],[e['lon']+off,e['lat']-.3],
            [e['lon']+off,e['lat']+.3],[e['lon']-off,e['lat']+.3],[e['lon']-off,e['lat']-.3]]]}} for e in exposure]
    gj = {'type':'FeatureCollection','name':'PAK_District_Exposure_Choropleth',
        'crs':{'type':'name','properties':{'name':'urn:ogc:def:crs:OGC:1.3:CRS84'}},'features':feats}
    with open(OUTPUT/'district_choropleth.geojson','w') as f: json.dump(gj,f,indent=2)
    log('B4 ✓ Saved → district_exposure_summary.csv | district_choropleth.geojson')
    return exposure

