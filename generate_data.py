def fetch_dem():
    log('B1 ► SRTM 30m DEM (OpenTopoData API)…')
    pts = [dict(lat=c[1],lon=c[0],type='cpec') for c in CPEC_COORDS] + \
          [dict(lat=d['lat'],lon=d['lon'],type='district',name=d['n']) for d in DISTRICTS]
    dem_pts = []
    for i in range(0, len(pts), 50):
        batch = pts[i:i+50]
        lstr = '|'.join(f"{p['lat']},{p['lon']}" for p in batch)
        try:
            r = requests.get(f'https://api.opentopodata.org/v1/srtm30m?locations={lstr}', timeout=18)
            if r.ok:
                for idx, res in enumerate(r.json().get('results',[])):
                    pt = batch[idx]
                    elev = res.get('elevation') or elev_est(pt['lat'],pt['lon'])
                    dem_pts.append({**pt,'elev':elev,'slope_cat':slope_cat(elev,pt['lat'])})
                log(f'B1 ✓ SRTM batch {i//50+1}: elevations fetched')
            else: raise ValueError(f'HTTP {r.status_code}')
        except Exception as e:
            log(f'B1 ⚠ SRTM batch {i//50+1}: {e} — using estimates')
            for pt in batch:
                e2 = elev_est(pt['lat'],pt['lon'])
                dem_pts.append({**pt,'elev':e2,'slope_cat':slope_cat(e2,pt['lat'])})
    elevs = [d['elev'] for d in dem_pts]
    log(f'B1 ✓ DEM: {len(dem_pts)} pts | {min(elevs)}–{max(elevs)} m ASL')
    with open(OUTPUT/'srtm_dem_profile.json','w') as f: json.dump(dem_pts,f,indent=2)
    # WorldPop confirmation
    try:
        r = requests.get('https://www.worldpop.org/rest/data/pop/wpgp?iso3=PAK&year=2020',timeout=12)
        if r.ok: log('B1 ✓ WorldPop API confirmed — Pakistan 2020')
    except: log('B1 ⚠ WorldPop API — using published estimates')
    return dem_pts

